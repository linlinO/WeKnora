package types

import "time"

// Knowledge evolution is deliberately separate from the answer feedback
// record. A user vote is an observation; a proposal is the reviewable change
// that may eventually become searchable knowledge.
const (
	EvolutionProposalDraft      = "draft"
	EvolutionProposalConflict   = "conflict"
	EvolutionProposalTesting    = "testing"
	EvolutionProposalReady      = "ready"
	EvolutionProposalPublishing = "publishing"
	EvolutionProposalPublished  = "published"
	EvolutionProposalRejected   = "rejected"
	EvolutionProposalFailed     = "failed"

	EvolutionConflictNone      = "none"
	EvolutionConflictDuplicate = "duplicate"
	EvolutionConflictPossible  = "possible"
	EvolutionConflictConfirmed = "confirmed"

	EvolutionRelationSupersedes = "supersedes"
	EvolutionRelationDerived    = "derived_from"

	EvolutionTestCritical = "critical"
	EvolutionTestNormal   = "normal"
	EvolutionTestPending  = "pending"
	EvolutionTestPassed   = "passed"
	EvolutionTestFailed   = "failed"
)

// KnowledgeEvolutionProposal is the reviewable correction draft generated
// from an answer feedback record. It is tenant-scoped and immutable enough to
// preserve the evidence that the reviewer saw at creation time.
type KnowledgeEvolutionProposal struct {
	ID                    string     `json:"id" gorm:"type:varchar(36);primaryKey"`
	TenantID              uint64     `json:"tenant_id" gorm:"index"`
	KnowledgeBaseID       string     `json:"knowledge_base_id" gorm:"type:varchar(36);index"`
	FeedbackID            string     `json:"feedback_id" gorm:"type:varchar(36);index"`
	Question              string     `json:"question" gorm:"type:text"`
	QuestionHash          string     `json:"question_hash" gorm:"type:varchar(64);index"`
	OriginalAnswer        string     `json:"original_answer" gorm:"type:text"`
	CandidateAnswer       string     `json:"candidate_answer" gorm:"type:text"`
	SimilarQuestions      JSON       `json:"similar_questions" gorm:"type:json"`
	Status                string     `json:"status" gorm:"type:varchar(20);index"`
	ConflictStatus        string     `json:"conflict_status" gorm:"type:varchar(20);index"`
	ConflictSummary       string     `json:"conflict_summary" gorm:"type:text"`
	ConflictKnowledgeIDs  JSON       `json:"conflict_knowledge_ids" gorm:"type:json"`
	VersionGroupID        string     `json:"version_group_id" gorm:"type:varchar(36);index"`
	SupersedesKnowledgeID string     `json:"supersedes_knowledge_id" gorm:"type:varchar(36);index"`
	CorrectionKnowledgeID string     `json:"correction_knowledge_id" gorm:"type:varchar(36);index"`
	RegressionRunID       string     `json:"regression_run_id" gorm:"type:varchar(36)"`
	AutoGenerated         bool       `json:"auto_generated"`
	CreatedBy             string     `json:"created_by" gorm:"type:varchar(128)"`
	ReviewerID            string     `json:"reviewer_id" gorm:"type:varchar(128)"`
	ReviewNote            string     `json:"review_note" gorm:"type:text"`
	CreatedAt             time.Time  `json:"created_at"`
	UpdatedAt             time.Time  `json:"updated_at"`
	PublishedAt           *time.Time `json:"published_at,omitempty"`
}

func (KnowledgeEvolutionProposal) TableName() string { return "knowledge_evolution_proposals" }

// KnowledgeVersionLink records logical replacement without deleting the old
// knowledge row. The old row can be restored by reversing the active flag.
type KnowledgeVersionLink struct {
	ID              string    `json:"id" gorm:"type:varchar(36);primaryKey"`
	TenantID        uint64    `json:"tenant_id" gorm:"index"`
	KnowledgeBaseID string    `json:"knowledge_base_id" gorm:"type:varchar(36);index"`
	VersionGroupID  string    `json:"version_group_id" gorm:"type:varchar(36);index"`
	OldKnowledgeID  string    `json:"old_knowledge_id" gorm:"type:varchar(36);index"`
	NewKnowledgeID  string    `json:"new_knowledge_id" gorm:"type:varchar(36);index"`
	RelationType    string    `json:"relation_type" gorm:"type:varchar(20)"`
	Active          bool      `json:"active"`
	CreatedBy       string    `json:"created_by" gorm:"type:varchar(128)"`
	CreatedAt       time.Time `json:"created_at"`
}

func (KnowledgeVersionLink) TableName() string { return "knowledge_version_links" }

// KnowledgeRegressionCase is a durable question/expected-facts pair. Cases
// are created from feedback first and can later be promoted by an administrator
// to a critical acceptance test.
type KnowledgeRegressionCase struct {
	ID              string    `json:"id" gorm:"type:varchar(36);primaryKey"`
	TenantID        uint64    `json:"tenant_id" gorm:"index"`
	KnowledgeBaseID string    `json:"knowledge_base_id" gorm:"type:varchar(36);index"`
	ProposalID      string    `json:"proposal_id" gorm:"type:varchar(36);index"`
	Question        string    `json:"question" gorm:"type:text"`
	ExpectedAnswer  string    `json:"expected_answer" gorm:"type:text"`
	Severity        string    `json:"severity" gorm:"type:varchar(20);default:'normal'"`
	Enabled         bool      `json:"enabled"`
	CreatedAt       time.Time `json:"created_at"`
	UpdatedAt       time.Time `json:"updated_at"`
}

func (KnowledgeRegressionCase) TableName() string { return "knowledge_regression_cases" }

// KnowledgeRegressionRun records the gate result used by the publish action.
type KnowledgeRegressionRun struct {
	Kind            string     `json:"kind" gorm:"default:'legacy_text'"`
	CandidateHash   string     `json:"candidate_hash"`
	AgentID         string     `json:"agent_id"`
	ModelID         string     `json:"model_id"`
	ConfigHash      string     `json:"config_hash"`
	Input           JSON       `json:"input" gorm:"type:jsonb"`
	ID              string     `json:"id" gorm:"type:varchar(36);primaryKey"`
	TenantID        uint64     `json:"tenant_id" gorm:"index"`
	KnowledgeBaseID string     `json:"knowledge_base_id" gorm:"type:varchar(36);index"`
	ProposalID      string     `json:"proposal_id" gorm:"type:varchar(36);index"`
	Status          string     `json:"status" gorm:"type:varchar(20)"`
	Total           int        `json:"total"`
	Passed          int        `json:"passed"`
	CriticalTotal   int        `json:"critical_total"`
	CriticalPassed  int        `json:"critical_passed"`
	FailureSummary  string     `json:"failure_summary" gorm:"type:text"`
	StartedAt       time.Time  `json:"started_at"`
	CompletedAt     *time.Time `json:"completed_at,omitempty"`
}

func (KnowledgeRegressionRun) TableName() string { return "knowledge_regression_runs" }

