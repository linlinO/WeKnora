func (h *KnowledgeEvolutionHandler) Publish(c *gin.Context) {
	ctx := c.Request.Context()
	caller := types.CallerFromContext(ctx)
	var req evolutionPublishRequest
	if err := c.ShouldBindJSON(&req); err != nil {
		c.JSON(http.StatusBadRequest, gin.H{"message": "发布参数不合法"})
		return
	}
	proposal, err := h.loadProposal(ctx, caller.TenantID, c.Param("id"))
	if err != nil {
		c.JSON(http.StatusNotFound, gin.H{"message": "演进草稿不存在"})
		return
	}
	if !h.editableProposal(c, proposal) {
		return
	}
	answer := strings.TrimSpace(req.Answer)
	if answer == "" {
		answer = strings.TrimSpace(proposal.CandidateAnswer)
	}
	if answer == "" || h.knowledgeService == nil {
		c.JSON(http.StatusBadRequest, gin.H{"message": "请填写标准答案"})
		return
	}
	if proposal.ConflictStatus == types.EvolutionConflictConfirmed && !req.ConfirmConflict && !req.Force {
		c.JSON(http.StatusConflict, gin.H{"message": "检测到答案冲突，请确认后再发布"})
		return
	}
	if proposal.RegressionRunID == "" {
		c.JSON(http.StatusConflict, gin.H{"message": "请先运行回归测试"})
		return
	}
	if proposal.RegressionRunID != "" {
		var run types.KnowledgeRegressionRun
		if err := h.db.WithContext(ctx).Where("id = ? AND tenant_id = ? AND proposal_id = ?", proposal.RegressionRunID, caller.TenantID, proposal.ID).First(&run).Error; err != nil || run.Status != types.EvolutionTestPassed {
			c.JSON(http.StatusConflict, gin.H{"message": "回归测试未通过，不能发布"})
			return
		}
		var tested []types.KnowledgeRegressionResult
		if err := h.db.WithContext(ctx).Where("run_id = ?", run.ID).Find(&tested).Error; err != nil || len(tested) == 0 {
			c.JSON(http.StatusConflict, gin.H{"message": "缺少有效的测试结果，请重新测试"})
			return
		}
		if run.Kind != "preview" || run.CandidateHash != replayHash(answer) {
			c.JSON(http.StatusConflict, gin.H{"message": "请对当前答案运行发布前问答预演，旧文本检查不能作为发布依据"})
			return
		}
		var testedInput replayInput
		if json.Unmarshal(run.Input, &testedInput) != nil || testedInput.ExpectedBehavior == "clarification" {
			c.JSON(409, gin.H{"message": "追问测试不能代替答案验证，请补全问题并完成回答预演后发布"})
			return
		}
		if h.agents != nil {
			a, e := h.agents.GetAgentByID(ctx, run.AgentID)
			if e != nil || a == nil || replayConfigHash(a) != run.ConfigHash {
				c.JSON(409, gin.H{"message": "智能体配置已变更，请重新预演"})
				return
			}
		}
	}
	title := strings.TrimSpace(req.Title)
	if title == "" {
		title = "知识纠错：" + proposal.Question
	}
	proposal.Status = types.EvolutionProposalPublishing
	proposal.CandidateAnswer = answer
	proposal.ReviewerID = caller.UserID
	proposal.ReviewNote = strings.TrimSpace(req.Note)
	proposal.UpdatedAt = time.Now().UTC()
	lock := h.db.WithContext(ctx).Model(&types.KnowledgeEvolutionProposal{}).
		Where("id = ? AND tenant_id = ? AND status NOT IN ? AND regression_run_id = ? AND candidate_answer = ?", proposal.ID, caller.TenantID,
			[]string{types.EvolutionProposalPublished, types.EvolutionProposalPublishing, types.EvolutionProposalRejected}, proposal.RegressionRunID, answer).
		Updates(map[string]interface{}{"status": proposal.Status, "reviewer_id": proposal.ReviewerID, "review_note": proposal.ReviewNote, "updated_at": proposal.UpdatedAt})
	if lock.Error != nil || lock.RowsAffected != 1 {
		c.JSON(http.StatusInternalServerError, gin.H{"message": "锁定发布任务失败"})
		return
	}
	content := buildEvolutionMarkdown(proposal.Question, answer)
	knowledge, err := h.knowledgeService.CreateKnowledgeFromManual(ctx, proposal.KnowledgeBaseID, &types.ManualKnowledgePayload{
		Title: title, Content: content, Status: types.ManualKnowledgeStatusPublish, Channel: types.ChannelAPI,
	}, types.ChannelAPI)
	if err != nil {
		proposal.Status = types.EvolutionProposalFailed
		proposal.UpdatedAt = time.Now().UTC()
		_ = h.db.WithContext(ctx).Save(proposal).Error
		c.JSON(http.StatusInternalServerError, gin.H{"message": "发布纠错知识失败"})
		return
	}
	if proposal.SupersedesKnowledgeID != "" && proposal.SupersedesKnowledgeID != knowledge.ID {
		var old types.Knowledge
		if err := h.db.WithContext(ctx).Where("id = ? AND tenant_id = ? AND knowledge_base_id = ? AND deleted_at IS NULL",
			proposal.SupersedesKnowledgeID, caller.TenantID, proposal.KnowledgeBaseID).First(&old).Error; err == nil {
			// Search result assembly filters disabled knowledge, so the old vector
			// can remain for audit/rollback without being returned to users.
			_ = h.db.WithContext(ctx).Model(&types.Knowledge{}).Where("id = ?", old.ID).Update("enable_status", "disabled").Error
			_ = h.db.WithContext(ctx).Create(&types.KnowledgeVersionLink{
				ID: uuid.NewString(), TenantID: caller.TenantID, KnowledgeBaseID: proposal.KnowledgeBaseID,
				VersionGroupID: proposal.VersionGroupID, OldKnowledgeID: old.ID, NewKnowledgeID: knowledge.ID,
				RelationType: types.EvolutionRelationSupersedes, Active: true, CreatedBy: caller.UserID, CreatedAt: time.Now().UTC(),
			}).Error
		}
	}
	now := time.Now().UTC()
	proposal.Status = types.EvolutionProposalPublished
	proposal.CorrectionKnowledgeID = knowledge.ID
	proposal.PublishedAt = &now
	proposal.UpdatedAt = now
	if err := h.db.WithContext(ctx).Save(proposal).Error; err != nil {
		c.JSON(http.StatusInternalServerError, gin.H{"message": "知识已发布，但演进状态保存失败"})
		return
	}
	_ = h.db.WithContext(ctx).Model(&types.AnswerFeedback{}).Where("id = ? AND tenant_id = ?", proposal.FeedbackID, caller.TenantID).
		Updates(map[string]interface{}{"status": types.AnswerFeedbackResolved, "reviewer_id": caller.UserID, "correction_knowledge_id": knowledge.ID, "knowledge_base_id": proposal.KnowledgeBaseID, "updated_at": now}).Error
	c.JSON(http.StatusOK, gin.H{"success": true, "data": proposal, "knowledge_id": knowledge.ID})
}

func (h *KnowledgeEvolutionHandler) editableProposal(c *gin.Context, proposal *types.KnowledgeEvolutionProposal) bool {
	if proposal.Status == types.EvolutionProposalPublished || proposal.Status == types.EvolutionProposalPublishing || proposal.Status == types.EvolutionProposalRejected {
		c.JSON(http.StatusConflict, gin.H{"message": "该版本已发布、正在发布或已回滚，不能继续修改"})
		return false
	}
	var row types.AnswerFeedback
	if err := h.db.WithContext(c.Request.Context()).Where("tenant_id = ? AND id = ?", proposal.TenantID, proposal.FeedbackID).First(&row).Error; err != nil ||
		(row.Status != types.AnswerFeedbackPending && row.Status != types.AnswerFeedbackCorrecting) {
		c.JSON(http.StatusConflict, gin.H{"message": "反馈已处理或已撤回，请刷新"})
		return false
	}
	return true
}

// SaveDraft persists reviewer edits without generating or publishing knowledge.
func (h *KnowledgeEvolutionHandler) SaveDraft(c *gin.Context) {
	caller := types.CallerFromContext(c.Request.Context())
	proposal, err := h.loadProposal(c.Request.Context(), caller.TenantID, c.Param("id"))
	if err != nil {
		c.JSON(http.StatusNotFound, gin.H{"message": "草稿不存在"})
		return
	}
	if !h.editableProposal(c, proposal) {
		return
	}
	var req evolutionRegressionRequest
	if err := c.ShouldBindJSON(&req); err != nil {
		c.JSON(http.StatusBadRequest, gin.H{"message": "草稿格式不合法"})
		return
	}
	answer := strings.TrimSpace(req.Answer)
	updates := map[string]interface{}{"candidate_answer": answer, "updated_at": time.Now().UTC()}
	if answer != proposal.CandidateAnswer {
		updates["regression_run_id"] = ""
		updates["status"] = types.EvolutionProposalDraft
	}
	result := h.db.WithContext(c.Request.Context()).Model(proposal).
		Where("status NOT IN ?", []string{types.EvolutionProposalPublished, types.EvolutionProposalPublishing, types.EvolutionProposalRejected}).Updates(updates)
	if result.Error != nil || result.RowsAffected != 1 {
		c.JSON(http.StatusConflict, gin.H{"message": "草稿状态已改变，请刷新"})
		return
	}
	c.JSON(http.StatusOK, gin.H{"success": true, "data": proposal})
}

func (h *KnowledgeEvolutionHandler) Rollback(c *gin.Context) {
	ctx := c.Request.Context()
	caller := types.CallerFromContext(ctx)
	proposal, err := h.loadProposal(ctx, caller.TenantID, c.Param("id"))
	if err != nil || proposal.CorrectionKnowledgeID == "" {
		c.JSON(http.StatusNotFound, gin.H{"message": "已发布版本不存在"})
		return
	}
	var link types.KnowledgeVersionLink
	if err := h.db.WithContext(ctx).Where("tenant_id = ? AND new_knowledge_id = ? AND active = ?", caller.TenantID, proposal.CorrectionKnowledgeID, true).First(&link).Error; err != nil {
		c.JSON(http.StatusBadRequest, gin.H{"message": "该版本没有可回滚的旧版本"})
		return
	}
	if err := h.db.WithContext(ctx).Transaction(func(tx *gorm.DB) error {
		if err := tx.Model(&types.KnowledgeVersionLink{}).Where("id = ?", link.ID).Update("active", false).Error; err != nil {
			return err
		}
		if err := tx.Model(&types.Knowledge{}).Where("id = ? AND tenant_id = ?", link.OldKnowledgeID, caller.TenantID).Update("enable_status", "enabled").Error; err != nil {
			return err
		}
		return tx.Model(&types.Knowledge{}).Where("id = ? AND tenant_id = ?", link.NewKnowledgeID, caller.TenantID).Update("enable_status", "disabled").Error
	}); err != nil {
		c.JSON(http.StatusInternalServerError, gin.H{"message": "回滚失败"})
		return
	}
	proposal.Status = types.EvolutionProposalRejected
	proposal.ReviewNote = strings.TrimSpace(c.PostForm("note"))
	proposal.UpdatedAt = time.Now().UTC()
	_ = h.db.WithContext(ctx).Save(proposal).Error
	c.JSON(http.StatusOK, gin.H{"success": true, "data": proposal})
}

func (h *KnowledgeEvolutionHandler) loadProposal(ctx context.Context, tenantID uint64, id string) (*types.KnowledgeEvolutionProposal, error) {
	var row types.KnowledgeEvolutionProposal
	if err := h.db.WithContext(ctx).Where("id = ? AND tenant_id = ?", id, tenantID).First(&row).Error; err != nil {
		return nil, err
	}
	return &row, nil
}

func buildEvolutionMarkdown(question, answer string) string {
	return fmt.Sprintf("# 权威纠错条目\n\n## 用户问题\n%s\n\n## 标准答案\n%s\n", strings.TrimSpace(question), strings.TrimSpace(answer))
}
