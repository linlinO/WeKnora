// KnowledgeEvolutionHandler owns the review-gated correction workflow. It is
// separate from AnswerFeedbackHandler so the existing feedback API remains
// backwards compatible while new clients use proposals and version links.
type KnowledgeEvolutionHandler struct {
	sessions         interfaces.SessionService
	agents           interfaces.CustomAgentService
	runCase          func(context.Context, *types.KnowledgeEvolutionProposal, *types.CustomAgent, string, string) (replayAnswer, error)
	judge            func(context.Context, string, string, string, string) (bool, string, error)
	db               *gorm.DB
	modelService     interfaces.ModelService
	knowledgeService interfaces.KnowledgeService
	kbService        interfaces.KnowledgeBaseService
}

func NewKnowledgeEvolutionHandler(
	db *gorm.DB,
	modelService interfaces.ModelService,
	knowledgeService interfaces.KnowledgeService,
	kbService interfaces.KnowledgeBaseService,
) *KnowledgeEvolutionHandler {
	return &KnowledgeEvolutionHandler{db: db, modelService: modelService, knowledgeService: knowledgeService, kbService: kbService}
}

type evolutionDraftRequest struct {
	KnowledgeBaseID string `json:"knowledge_base_id" binding:"required"`
}

type evolutionPublishRequest struct {
	Answer          string `json:"answer"`
	Title           string `json:"title"`
	Note            string `json:"note"`
	Force           bool   `json:"force"`
	ConfirmConflict bool   `json:"confirm_conflict"`
}

type evolutionRegressionRequest struct {
	Answer string `json:"answer"`
}

// CreateDraft creates at most one proposal for a feedback record. When a chat
// model is configured on the target KB it generates a candidate answer; if the
// model is unavailable, the reviewer receives a safe editable copy instead of
// losing the feedback.
func (h *KnowledgeEvolutionHandler) CreateDraft(c *gin.Context) {
	ctx := c.Request.Context()
	caller := types.CallerFromContext(ctx)
	if caller.TenantID == 0 {
		c.JSON(http.StatusUnauthorized, gin.H{"message": "未识别到工作空间"})
		return
	}
	var req evolutionDraftRequest
	if err := c.ShouldBindJSON(&req); err != nil {
		c.JSON(http.StatusBadRequest, gin.H{"message": "知识库不能为空"})
		return
	}
	var feedback types.AnswerFeedback
	if err := h.db.WithContext(ctx).Where("id = ? AND tenant_id = ?", c.Param("feedback_id"), caller.TenantID).First(&feedback).Error; err != nil {
		c.JSON(http.StatusNotFound, gin.H{"message": "反馈记录不存在"})
		return
	}
	var existing types.KnowledgeEvolutionProposal
	if err := h.db.WithContext(ctx).Where("tenant_id = ? AND feedback_id = ?", caller.TenantID, feedback.ID).First(&existing).Error; err == nil {
		c.JSON(http.StatusOK, gin.H{"success": true, "data": existing})
		return
	} else if !errors.Is(err, gorm.ErrRecordNotFound) {
		c.JSON(http.StatusInternalServerError, gin.H{"message": "读取纠错草稿失败"})
		return
	}
	if feedback.Status != types.AnswerFeedbackPending && feedback.Status != types.AnswerFeedbackCorrecting {
		c.JSON(http.StatusConflict, gin.H{"message": "反馈已处理或撤回，不能创建纠错草稿"})
		return
	}
	if feedback.Rating == types.AnswerFeedbackUseful && feedback.Status != types.AnswerFeedbackCorrecting {
		c.JSON(http.StatusConflict, gin.H{"message": "有用反馈请先转入纠错处理"})
		return
	}
	if h.kbService == nil || h.db == nil {
		c.JSON(http.StatusInternalServerError, gin.H{"message": "知识演进服务未配置"})
		return
	}
	kb, err := h.kbService.GetKnowledgeBaseByID(ctx, strings.TrimSpace(req.KnowledgeBaseID))
	if err != nil || kb == nil {
		c.JSON(http.StatusBadRequest, gin.H{"message": "目标知识库不存在或无权访问"})
		return
	}

	candidate, generated := h.generateCandidate(ctx, kb, &feedback)
	question := strings.TrimSpace(feedback.Question)
	proposal := &types.KnowledgeEvolutionProposal{
		ID:                   uuid.NewString(),
		TenantID:             caller.TenantID,
		KnowledgeBaseID:      kb.ID,
		FeedbackID:           feedback.ID,
		Question:             question,
		QuestionHash:         evolution.QuestionHash(question),
		OriginalAnswer:       feedback.Answer,
		CandidateAnswer:      candidate,
		Status:               types.EvolutionProposalDraft,
		ConflictStatus:       types.EvolutionConflictNone,
		SimilarQuestions:     types.JSON([]byte("[]")),
		ConflictKnowledgeIDs: types.JSON([]byte("[]")),
		VersionGroupID:       uuid.NewString(),
		AutoGenerated:        generated,
		CreatedBy:            caller.UserID,
		CreatedAt:            time.Now().UTC(),
		UpdatedAt:            time.Now().UTC(),
	}

	if err := h.populateConflicts(ctx, proposal); err != nil {
		c.JSON(http.StatusInternalServerError, gin.H{"message": "检查重复知识失败"})
		return
	}
	if err := h.db.WithContext(ctx).Transaction(func(tx *gorm.DB) error {
		update := tx.Model(&types.AnswerFeedback{}).Where("id = ? AND tenant_id = ? AND status IN ?", feedback.ID, caller.TenantID,
			[]string{types.AnswerFeedbackPending, types.AnswerFeedbackCorrecting}).Update("status", types.AnswerFeedbackCorrecting)
		if update.Error != nil {
			return update.Error
		}
		if update.RowsAffected != 1 {
			return errors.New("feedback no longer editable")
		}
		return tx.Create(proposal).Error
	}); err != nil {
		c.JSON(http.StatusInternalServerError, gin.H{"message": "保存纠错草稿失败"})
		return
	}
	if err := h.ensureRegressionCase(ctx, proposal, feedback.Reason); err != nil {
		logger.Warnf(ctx, "create evolution regression case failed: %v", err)
	}
	c.JSON(http.StatusCreated, gin.H{"success": true, "data": proposal})
}

func (h *KnowledgeEvolutionHandler) generateCandidate(ctx context.Context, kb *types.KnowledgeBase, feedback *types.AnswerFeedback) (string, bool) {
	fallback := strings.TrimSpace(feedback.Answer)
	if fallback == "" {
		fallback = strings.TrimSpace(feedback.Reason)
	}
	if h.modelService == nil || kb == nil || strings.TrimSpace(kb.SummaryModelID) == "" {
		return fallback, false
	}
	model, err := h.modelService.GetChatModel(ctx, kb.SummaryModelID)
	if err != nil || model == nil {
		logger.Warnf(ctx, "evolution draft model unavailable: %v", err)
		return fallback, false
	}
	reason := strings.TrimSpace(feedback.Reason)
	prompt := "你是企业知识库审核助手。根据用户问题、原回答和反馈，生成可供管理员审核的标准答案草稿。只输出答案正文，不要解释你在生成草稿，也不要编造原文没有依据的事实。若证据不足，明确写出需要人工确认。\n\n用户问题：" + feedback.Question + "\n\n原回答：" + feedback.Answer + "\n\n用户反馈：" + reason
	think := false
	response, err := model.Chat(ctx, []chat.Message{{Role: "user", Content: prompt}}, &chat.ChatOptions{
		Temperature: 0.2, MaxTokens: 1200, Thinking: &think,
	})
	if err != nil || response == nil || strings.TrimSpace(response.Content) == "" {
		logger.Warnf(ctx, "evolution draft generation failed: %v", err)
		return fallback, false
	}
	return strings.TrimSpace(response.Content), true
}

func (h *KnowledgeEvolutionHandler) populateConflicts(ctx context.Context, proposal *types.KnowledgeEvolutionProposal) error {
	var same []types.KnowledgeEvolutionProposal
	if err := h.db.WithContext(ctx).
		Where("tenant_id = ? AND knowledge_base_id = ? AND question_hash = ? AND status NOT IN ?",
			proposal.TenantID, proposal.KnowledgeBaseID, proposal.QuestionHash, []string{types.EvolutionProposalRejected, types.EvolutionProposalFailed}).
		Order("created_at DESC").Limit(10).Find(&same).Error; err != nil {
		return err
	}
	var ids []string
	for _, previous := range same {
		if previous.ID == proposal.ID {
			continue
		}
		if previous.CorrectionKnowledgeID != "" {
			ids = append(ids, previous.CorrectionKnowledgeID)
		}
		proposal.VersionGroupID = previous.VersionGroupID
		proposal.SupersedesKnowledgeID = previous.CorrectionKnowledgeID
		coverage := evolution.TokenCoverage(previous.CandidateAnswer, proposal.CandidateAnswer)
		if coverage >= 0.85 {
			proposal.ConflictStatus = types.EvolutionConflictDuplicate
			proposal.ConflictSummary = "检测到相同问题的高度相似纠错答案，建议合并或直接使用已有版本"
		} else {
			proposal.ConflictStatus = types.EvolutionConflictConfirmed
			proposal.ConflictSummary = "检测到相同问题但答案差异较大，发布前必须确认新版本是否替代旧版本"
		}
		break
	}
	// Existing manually published corrections from older releases did not have
	// a proposal row. Match their stable title so the first new proposal still
	// establishes a version chain.
	if proposal.SupersedesKnowledgeID == "" && proposal.Question != "" {
		var old types.Knowledge
		if err := h.db.WithContext(ctx).Where("tenant_id = ? AND knowledge_base_id = ? AND title = ? AND deleted_at IS NULL",
			proposal.TenantID, proposal.KnowledgeBaseID, "知识纠错："+proposal.Question).Order("updated_at DESC").First(&old).Error; err == nil {
			proposal.SupersedesKnowledgeID = old.ID
			ids = append(ids, old.ID)
			proposal.ConflictStatus = types.EvolutionConflictPossible
			proposal.ConflictSummary = "检测到历史纠错知识，发布后将建立版本替代关系"
		}
	}
	encoded, err := json.Marshal(ids)
	if err != nil {
		return err
	}
	proposal.ConflictKnowledgeIDs = types.JSON(encoded)
	return nil
}

func (h *KnowledgeEvolutionHandler) ensureRegressionCase(ctx context.Context, proposal *types.KnowledgeEvolutionProposal, reason string) error {
	var count int64
	if err := h.db.WithContext(ctx).Model(&types.KnowledgeRegressionCase{}).
		Where("tenant_id = ? AND knowledge_base_id = ? AND question = ?", proposal.TenantID, proposal.KnowledgeBaseID, proposal.Question).Count(&count).Error; err != nil {
		return err
	}
	if count > 0 {
		return nil
	}
	severity := types.EvolutionTestNormal
	if strings.Contains(reason, "内容有错误") || strings.Contains(reason, "数据分析错误") {
		severity = types.EvolutionTestCritical
	}
	return h.db.WithContext(ctx).Create(&types.KnowledgeRegressionCase{
		ID: uuid.NewString(), TenantID: proposal.TenantID, KnowledgeBaseID: proposal.KnowledgeBaseID,
		ProposalID: proposal.ID, Question: proposal.Question, ExpectedAnswer: proposal.CandidateAnswer,
		Severity: severity, Enabled: true, CreatedAt: time.Now().UTC(), UpdatedAt: time.Now().UTC(),
	}).Error
}

// List returns proposals for the current tenant. The route is admin-only.
func (h *KnowledgeEvolutionHandler) List(c *gin.Context) {
	caller := types.CallerFromContext(c.Request.Context())
	status := strings.TrimSpace(c.DefaultQuery("status", "all"))
	query := h.db.WithContext(c.Request.Context()).Where("tenant_id = ?", caller.TenantID)
	if status != "" && status != "all" {
		query = query.Where("status = ?", status)
	}
	var rows []*types.KnowledgeEvolutionProposal
	if err := query.Order("created_at DESC").Limit(200).Find(&rows).Error; err != nil {
		c.JSON(http.StatusInternalServerError, gin.H{"message": "读取演进草稿失败"})
		return
	}
	c.JSON(http.StatusOK, gin.H{"data": rows, "total": len(rows)})
}

